#!/usr/bin/env node
// pi-agents — one-line installer for the pi-agents pi extension.
//
// Usage:
//   pi-agents [install] [dir]     install into dir (default: current directory)
//   pi-agents --global            install for all projects (user scope, ~/.pi/agent/settings.json)
//   pi-agents --legacy            classic install: symlink into <dir>/.pi/extensions/pi-agents/
//   pi-agents --agents            also install the bundled sample agents (<dir>/.pi-agents/)
//   pi-agents remove [dir]        uninstall (use the same scope flags you installed with)
//   pi-agents status [dir]        show install state
//   pi-agents --repo <path>       extension sources (default: this checkout / baked at build)
//   pi-agents --yes               pass --approve to pi (auto-trust)
//   pi-agents --force             overwrite existing files
//   pi-agents --help | --version  this help / version
//
// Default install delegates to pi's package manager (`pi install <repo> [-l]`):
// the repo path is recorded in <dir>/.pi/settings.json and the extension is
// loaded from the repo directly — nothing is copied and the target project
// needs no node_modules of its own. `--legacy` keeps the classic symlink
// layout (<dir>/.pi/extensions/pi-agents/) for pi setups without the
// package manager or when you prefer auto-discovery.
//
// Zero runtime dependencies (node builtins only); runs as a script or as a
// bun-compiled binary (scripts/build.sh bakes the repo path in).

import * as fs from "node:fs";
import * as os from "node:os";
import * as path from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";

const EXT = "pi-agents";
const FILES = ["index.ts", "agents.ts", "mcp.ts", "ui.ts", "guide.md"];
const COMMANDS = ["install", "remove", "uninstall", "status", "check", "list"];
const RESET = "\x1b[0m";
const C = { green: "\x1b[32m", yellow: "\x1b[33m", red: "\x1b[31m", dim: "\x1b[2m", bold: "\x1b[1m", cyan: "\x1b[36m" };
const useColor = process.stdout.isTTY;
const paint = (s, c) => (useColor ? c + s + RESET : s);
const out = (s = "", c) => console.log(c ? paint(s, c) : s);
const fail = (msg) => { out(`error: ${msg}`, C.red); process.exit(1); };

// ---------------------------------------------------------------------------
// argument parsing

function parseArgs(argv) {
  const opts = { command: "install", dir: null, repo: null, global: false, legacy: false, agents: false, yes: false, force: false, help: false, version: false };
  const positional = [];
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    switch (a) {
      case "-h": case "--help": opts.help = true; break;
      case "-v": case "--version": opts.version = true; break;
      case "-g": case "--global": opts.global = true; break;
      case "-l": case "--legacy": opts.legacy = true; break;
      case "-a": case "--agents": opts.agents = true; break;
      case "-y": case "--yes": opts.yes = true; break;
      case "-f": case "--force": opts.force = true; break;
      case "--repo": opts.repo = argv[++i]; if (!opts.repo) fail("--repo needs a path"); break;
      default:
        if (a.startsWith("-")) fail(`unknown option: ${a}`);
        positional.push(a);
    }
  }
  if (positional.length > 2) fail(`too many arguments: ${positional.join(" ")}`);
  if (positional[0] && !COMMANDS.includes(positional[0])) {
    // bare path: `pi-agents /path/to/project` == `pi-agents install /path/to/project`
    opts.dir = positional[0];
  } else {
    if (positional[0] === "uninstall") opts.command = "remove";
    else if (positional[0]) opts.command = positional[0];
    opts.dir = positional[1] ?? null;
  }
  return opts;
}

// ---------------------------------------------------------------------------
// locating the extension sources

async function resolveRepo(explicit) {
  if (explicit) return path.resolve(explicit);
  if (process.env.PI_AGENTS_REPO) return path.resolve(process.env.PI_AGENTS_REPO);
  let baked = null;
  try {
    baked = (await import("./_baked.mjs")).BAKED_REPO || null; // generated by scripts/build.sh
  } catch { /* source checkout without baked file */ }
  if (baked) return path.resolve(baked);
  const here = fileURLToPath(import.meta.url);
  if (here.includes("/$bunfs/")) return null; // compiled binary without baked repo
  const candidate = path.dirname(path.dirname(here)); // <repo>/bin/install.mjs -> <repo>
  return fs.existsSync(path.join(candidate, "index.ts")) ? candidate : null;
}

function requireRepo(repo) {
  if (!repo) fail("cannot locate pi-agents sources — pass --repo <path> or set PI_AGENTS_REPO");
  if (!fs.existsSync(path.join(repo, "index.ts"))) fail(`not a pi-agents checkout: ${repo} (missing index.ts)`);
  const missing = FILES.filter((f) => !fs.existsSync(path.join(repo, f)));
  if (missing.length) fail(`repo is missing extension files: ${missing.join(", ")}`);
  return repo;
}

function repoVersion(repo) {
  try {
    const pkg = JSON.parse(fs.readFileSync(path.join(repo, "package.json"), "utf8"));
    return pkg.version ?? "dev";
  } catch { return "dev"; }
}

// ---------------------------------------------------------------------------
// helpers

const userAgentDir = () => process.env.PI_AGENT_DIR || process.env.PI_CODING_AGENT_DIR || path.join(os.homedir(), ".pi", "agent");

// pi resolves trust entries against canonicalized (realpath) cwd — macOS /tmp is
// a symlink to /private/tmp, so keys must be realpaths to match.
const trustDecision = (dir) => {
  let key;
  try { key = fs.realpathSync(dir); } catch { return null; }
  let data = {};
  try { data = JSON.parse(fs.readFileSync(path.join(userAgentDir(), "trust.json"), "utf8")); } catch { return null; }
  let cur = key;
  while (true) {
    const v = data[cur];
    if (v === true || v === false) return v;
    const parent = path.dirname(cur);
    if (parent === cur) return null;
    cur = parent;
  }
};

// Equivalent to accepting pi's "Trust project folder?" prompt: records the decision
// in ~/.pi/agent/trust.json (atomically, ignoring pi's lock — single-shot CLI).
const persistTrust = (dir) => {
  const key = fs.realpathSync(dir);
  const storePath = path.join(userAgentDir(), "trust.json");
  let data = {};
  try { data = JSON.parse(fs.readFileSync(storePath, "utf8")); } catch { /* new store */ }
  if (data[key] === true) return;
  data[key] = true;
  const tmp = `${storePath}.tmp-${process.pid}`;
  fs.writeFileSync(tmp, `${JSON.stringify(data, null, 2)}\n`);
  fs.renameSync(tmp, storePath);
};
const piOnPath = () => {
  const r = spawnSync("pi", ["--version"], { stdio: "ignore" });
  return !r.error && r.status === 0;
};
const readSettings = (p) => {
  try { return JSON.parse(fs.readFileSync(p, "utf8")); } catch { return null; }
};
// settings entries for local sources are stored relative to the scope base dir
// (.pi/ for project scope, ~/.pi/agent/ for user scope)
const resolveSettingsPath = (entry, baseDir) => {
  const s = String(entry).trim();
  if (s.startsWith("local:")) return path.resolve(baseDir, s.slice(6));
  if (s.startsWith("npm:") || s.startsWith("git:") || s.startsWith("http")) return null;
  return path.resolve(baseDir, s);
};

// ---------------------------------------------------------------------------
// install

async function install(repo, dir, opts) {
  requireRepo(repo);
  out(`installing pi-agents ${repoVersion(repo)} from ${repo}`, C.dim);
  if (opts.legacy) legacyInstall(repo, dir, opts);
  else settingsInstall(repo, dir, opts);
  if (opts.agents) installSamples(repo, dir, opts);
  summary(dir, opts);
}

function runPi(args, dir) {
  out(`→ pi ${args.join(" ")}   (cwd: ${dir})`, C.dim);
  // stderr captured so we can detect the "not trusted" case and retry with --approve;
  // stdout stays inherited so any interactive prompts display.
  const r = spawnSync("pi", args, { cwd: dir, stdio: ["inherit", "inherit", "pipe"] });
  if (r.error) fail(`could not run pi: ${r.error.message}`);
  return r;
}

function settingsInstall(repo, dir, opts) {
  if (!piOnPath()) fail("`pi` not found on PATH — install pi first, or use --legacy for the symlink layout");
  const args = ["install", repo, ...(opts.global ? [] : ["-l"])];
  if (opts.yes && !opts.global) persistTrust(dir); // pre-approve: trust the project up front
  let r = runPi(args, dir);
  if (r.status !== 0 && !opts.global && /trusted/i.test(String(r.stderr ?? ""))) {
    // pi refuses to touch project settings for untrusted projects. Grant the same
    // decision the interactive "Trust project folder?" prompt would record, then retry.
    out(`project ${dir} is not yet trusted — recording trust (equivalent of accepting pi's trust prompt)`, C.yellow);
    persistTrust(dir);
    r = runPi([...args, "--approve"], dir);
  }
  if (r.status !== 0) fail(`\`pi install\` exited with status ${r.status}`);
  if (!opts.global && trustDecision(dir) !== true) {
    // installing created .pi/settings.json, which makes pi require a trust decision
    // at runtime; record it now so the extension actually loads (same as accepting
    // pi's "Trust project folder?" prompt on first start).
    persistTrust(dir);
    out(`recorded trust for ${dir}`, C.dim);
  }
}

function legacyInstall(repo, dir, opts) {
  if (!opts.global && trustDecision(dir) !== true) {
    persistTrust(dir); // .pi/extensions makes pi require a trust decision at runtime
    out(`recorded trust for ${dir}`, C.dim);
  }
  const destDir = path.join(dir, ".pi", "extensions", EXT);
  let present = [];
  if (fs.existsSync(destDir)) present = fs.readdirSync(destDir).filter((f) => FILES.includes(f));
  if (present.length === FILES.length && !opts.force) {
    out(`already installed → ${destDir} (all ${FILES.length} files present; --force to refresh)`, C.yellow);
    return;
  }
  fs.mkdirSync(destDir, { recursive: true });
  for (const f of FILES) {
    const link = path.join(destDir, f);
    try {
      fs.rmSync(link, { force: true });
      fs.symlinkSync(path.join(repo, f), link);
    } catch (e) { fail(`failed to link ${f}: ${e.message}`); }
  }
  out(`installed (legacy symlinks) → ${destDir}`, C.green);
}

function installSamples(repo, dir, opts) {
  const srcDir = path.join(repo, ".pi-agents");
  if (!fs.existsSync(srcDir)) { out("no sample agents in repo (skipped)", C.yellow); return; }
  const destDir = opts.global ? path.join(userAgentDir(), "pi-agents") : path.join(dir, ".pi-agents");
  const items = fs.readdirSync(srcDir).filter((n) => n !== ".env"); // never copy secrets
  let copied = 0, skipped = 0;
  for (const name of items) {
    const s = path.join(srcDir, name);
    const d = path.join(destDir, name);
    if (fs.existsSync(d) && !opts.force) { skipped++; continue; }
    fs.rmSync(d, { recursive: true, force: true });
    if (fs.statSync(s).isDirectory()) fs.cpSync(s, d, { recursive: true });
    else { fs.mkdirSync(path.dirname(d), { recursive: true }); fs.copyFileSync(s, d); }
    copied++;
  }
  // agent samples import `../../agents` (repo layout); make them work from any
  // project by pointing at the extension's agents.ts (absolute, resolved by jiti)
  if (fs.existsSync(destDir)) {
    for (const f of walkTs(destDir)) rewriteImport(f, repo);
  }
  if (copied) out(`sample agents installed → ${destDir} (${copied} item(s))`, C.green);
  if (skipped) out(`${skipped} existing item(s) in ${destDir} skipped (--force to overwrite)`, C.yellow);
}

function walkTs(dir, acc = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walkTs(p, acc);
    else if (e.name.endsWith(".ts")) acc.push(p);
  }
  return acc;
}

function rewriteImport(file, repo) {
  let src = fs.readFileSync(file, "utf8");
  const re = /from\s+["']\.\.\/\.\.\/agents["']/g;
  if (!re.test(src)) return;
  src = src.replace(re, `from ${JSON.stringify(path.join(repo, "agents"))}`);
  fs.writeFileSync(file, src);
  out(`  rewrote agent import in ${path.basename(path.dirname(file))}/${path.basename(file)}`, C.dim);
}

function summary(dir, opts) {
  out("");
  out("Next steps:", C.bold);
  out(`  1. Start pi in ${dir} — the extension loads automatically (trust already recorded)`);
  out(`  2. /reload if pi is already running there`);
  out(`  3. ctrl+shift+a → agent picker · alt+a → rotate · /agent dev · /agent:help <question>`);
  out(`  4. Agents: define project agents in ${path.join(dir, ".pi-agents")}/ or shared ones in ${path.join(userAgentDir(), "pi-agents")}/`);
  out("");
  out(`Manage: pi-agents status · pi-agents remove${opts.global ? " --global" : ""} · pi list · pi remove`, C.dim);
}

// ---------------------------------------------------------------------------
// remove

function remove(repo, dir, opts) {
  let done = false;
  if (opts.legacy) {
    done = legacyRemove(dir);
  } else if (piOnPath()) {
    const args = ["remove", repo ?? "", ...(opts.global ? [] : ["-l"])].filter(Boolean);
    let r = runPi(args, dir);
    if (r.status !== 0 && !opts.global && /trusted/i.test(String(r.stderr ?? ""))) {
      out(`project ${dir} is not yet trusted — recording trust, retrying`, C.yellow);
      persistTrust(dir);
      r = runPi([...args, "--approve"], dir);
    }
    if (r.status !== 0) {
      out(`\`pi remove\` exited with status ${r.status}`, C.yellow);
      process.exitCode = 1;
    } else {
      done = true;
    }
  } else {
    out("`pi` not found on PATH — nothing to remove", C.yellow);
  }
  if (!opts.legacy && !opts.global) legacyRemove(dir); // also drop a legacy layout if present in the target
  const agentsDir = opts.global ? path.join(userAgentDir(), "pi-agents") : path.join(dir, ".pi-agents");
  if (fs.existsSync(agentsDir)) out(`note: sample agents remain in ${agentsDir} — delete manually if unwanted`, C.dim);
  if (done) out("done", C.green);
}

function legacyRemove(dir) {
  const destDir = path.join(dir, ".pi", "extensions", EXT);
  if (!fs.existsSync(destDir)) return false;
  for (const f of FILES) fs.rmSync(path.join(destDir, f), { force: true });
  if (fs.readdirSync(destDir).length === 0) {
    fs.rmdirSync(destDir);
    const extensionsDir = path.dirname(destDir);
    if (fs.existsSync(extensionsDir) && fs.readdirSync(extensionsDir).length === 0) fs.rmdirSync(extensionsDir);
    const piDir = path.dirname(extensionsDir);
    if (fs.existsSync(piDir) && fs.readdirSync(piDir).length === 0) fs.rmdirSync(piDir);
  }
  out(`removed legacy install → ${destDir}`, C.green);
  return true;
}

// ---------------------------------------------------------------------------
// status

function status(repo, dir, opts) {
  const lines = [];
  const p = (label, value, ok) => lines.push(`  ${label}: ${ok ? paint(value, C.green) : paint(value, C.red)}`);
  lines.push(paint("pi-agents status", C.bold));
  lines.push(`  target: ${dir}`);
  const trusted = trustDecision(dir);
  lines.push(`  trusted by pi: ${trusted === true ? paint("yes", C.green) : paint(trusted === false ? "no (explicitly denied)" : "no (not recorded yet)", C.yellow)}`);
  p("pi on PATH", piOnPath() ? "yes" : "NO", piOnPath());
  if (repo) {
    const okRepo = fs.existsSync(path.join(repo, "index.ts"));
    p("repo", `${repo}${okRepo ? ` (v${repoVersion(repo)})` : " (missing!)"}`, okRepo);
  } else {
    lines.push(`  repo: unknown (--repo <path> or PI_AGENTS_REPO)`);
  }

  // project scope
  const projSettings = readSettings(path.join(dir, ".pi", "settings.json"));
  const projEntries = (projSettings?.packages ?? []).map(String).filter((s) => !s.startsWith("npm:") && !s.startsWith("git:"));
  if (projEntries.length) {
    for (const e of projEntries) {
      const abs = resolveSettingsPath(e, path.join(dir, ".pi"));
      p(`project (.pi/settings.json)`, abs ? (fs.existsSync(abs) ? e : `${e}  (missing!)`) : e, abs ? fs.existsSync(abs) : false);
    }
  } else {
    lines.push(`  project (.pi/settings.json): ${paint("no packages", C.dim)}`);
  }

  // user scope
  const userSettingsPath = path.join(userAgentDir(), "settings.json");
  const userEntries = (readSettings(userSettingsPath)?.packages ?? []).map(String).filter((s) => !s.startsWith("npm:") && !s.startsWith("git:"));
  if (userEntries.length) {
    for (const e of userEntries) {
      const abs = resolveSettingsPath(e, userAgentDir());
      p(`user (${userSettingsPath})`, abs ? (fs.existsSync(abs) ? e : `${e}  (missing!)`) : e, abs ? fs.existsSync(abs) : false);
    }
  } else {
    lines.push(`  user (${userSettingsPath}): ${paint("no packages", C.dim)}`);
  }

  // legacy layout
  const legacyDir = path.join(dir, ".pi", "extensions", EXT);
  if (fs.existsSync(legacyDir)) {
    const files = fs.readdirSync(legacyDir).filter((f) => FILES.includes(f));
    p("legacy symlinks", `${legacyDir} (${files.length}/${FILES.length} files)`, files.length === FILES.length);
  } else {
    lines.push(`  legacy symlinks: ${paint("none", C.dim)}`);
  }

  // sample agents
  const agentsDir = path.join(dir, ".pi-agents");
  if (fs.existsSync(agentsDir)) {
    lines.push(`  sample agents: ${agentsDir} (${fs.readdirSync(agentsDir).filter((n) => !n.startsWith(".")).join(", ")})`);
  } else {
    lines.push(`  sample agents: ${paint("none", C.dim)}`);
  }

  console.log(lines.join("\n"));
}

// ---------------------------------------------------------------------------
// usage / version

function usage() {
  out(`pi-agents — one-line installer for the pi-agents pi extension`);
  out("");
  out("Usage:");
  out("  pi-agents [install] [dir]      Install into dir (default: current dir)");
  out("  pi-agents --global             Install for all projects (~/.pi/agent/settings.json)");
  out("  pi-agents --legacy             Classic install: symlink into <dir>/.pi/extensions/pi-agents/");
  out("  pi-agents --agents             Also install sample agents into <dir>/.pi-agents/");
  out("  pi-agents remove [dir]         Uninstall (use the same scope flags you installed with)");
  out("  pi-agents status [dir]         Show install state");
  out("  pi-agents --repo <path>        Extension sources (default: this checkout / baked at build)");
  out("  pi-agents --yes                Pass --approve to pi (auto-trust)");
  out("  pi-agents --force              Overwrite existing files");
  out("  pi-agents --help, --version    This help / version");
  out("");
  out("Default install delegates to pi's package manager (\`pi install <repo> [-l]\`):");
  out("the repo path is recorded in <dir>/.pi/settings.json and the extension is");
  out("loaded from there — nothing is copied, the target needs no node_modules.");
}

// ---------------------------------------------------------------------------

async function main() {
  const opts = parseArgs(process.argv.slice(2));
  if (opts.help) { usage(); return; }
  const dir = path.resolve(opts.dir || process.cwd());
  const repo = await resolveRepo(opts.repo);
  if (opts.version) {
    out(repo ? `pi-agents ${repoVersion(repo)}` : "pi-agents (dev)");
    return;
  }
  if (opts.command === "install") {
    fs.mkdirSync(dir, { recursive: true }); // pi spawns with cwd=dir; must exist
    await install(repo, dir, opts);
  } else if (opts.command === "remove") {
    fs.mkdirSync(dir, { recursive: true });
    remove(repo, dir, opts);
  } else {
    if (!fs.existsSync(dir)) { out(`target does not exist: ${dir}`, C.red); process.exitCode = 1; return; }
    status(repo, dir, opts);
  }
}

main().catch((e) => fail(e?.message ?? String(e)));
